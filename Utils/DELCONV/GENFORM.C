    fprintf(fp,"  TextHeight = 14\n");
    j=0;
    prbutton(fp,j,j,40,56,4,4,j);
    j++;
    for (i=0;i<12;i++) {
        prbutton(fp,j,j,40,56,4+i*40+((i/4)*20)+80,4,j);
        j++;
    }
    for (i=0;i<14;i++) {
        if (i==13)
            prbutton(fp,j,j,80,56,4+i*40,64,j);
        else
            prbutton(fp,j,j,40,56,4+i*40,64,j);
        j++;
    }
    for (i=0;i<13;i++) {
        if (i==0)
            prbutton(fp,j,j,60,56,4,124,j);
        else
            prbutton(fp,j,j,40,56,24+i*40,124,j);
        j++;
    }
